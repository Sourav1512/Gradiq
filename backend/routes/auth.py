"""
routes/auth.py – Authentication endpoints
  POST /api/auth/register
  POST /api/auth/login
  GET  /api/auth/me
Uses bcrypt for secure password hashing and JWT for role-based sessions.
"""

import bcrypt
import hashlib
import hmac
from flask import Blueprint, request, jsonify, g
from database import get_db_connection
from auth_utils import generate_token, token_required
from student_codes import generate_student_code

auth_bp = Blueprint("auth", __name__)


def hash_password(password: str) -> str:
    """Hash a plaintext password using bcrypt with a generated salt."""
    salt = bcrypt.gensalt(rounds=12)
    return bcrypt.hashpw(password.encode("utf-8"), salt).decode("utf-8")


def verify_password(stored: str, provided: str) -> bool:
    """Verify a plaintext password against a stored bcrypt hash."""
    try:
        stored_bytes = stored.encode("utf-8") if isinstance(stored, str) else stored
        return bcrypt.checkpw(provided.encode("utf-8"), stored_bytes)
    except Exception:
        # Fallback for backward compatibility if old SHA-256 salt:hash format was stored
        try:
            if ":" in stored:
                salt, hashed = stored.split(":", 1)
                expected = hashlib.sha256((salt + provided).encode()).hexdigest()
                return hmac.compare_digest(hashed, expected)
        except Exception:
            pass
        return False


@auth_bp.route("/register", methods=["POST"])
def register():
    """
    Public registration endpoint.
    IMPORTANT: Public sign-ups are STRICTLY assigned the 'student' role.
    Self-assignment to 'admin' is prevented on the server side.
    """
    data = request.get_json() or {}
    if "student_id" in data or "student_code" in data or "id" in data:
        return jsonify({"error": "Student codes and database IDs are generated by the server."}), 400

    # Validate required fields
    required = ["full_name", "email", "password"]
    for field in required:
        if not str(data.get(field, "")).strip():
            return jsonify({"error": f"{field} is required"}), 400

    full_name = data["full_name"].strip()
    email     = data["email"].strip().lower()
    password  = str(data["password"])

    # Strict role enforcement: Always 'student' for public signups
    role = "student"

    if len(password) < 6:
        return jsonify({"error": "Password must be at least 6 characters"}), 400

    hashed = hash_password(password)

    conn = cursor = None
    try:
        conn   = get_db_connection()
        cursor = conn.cursor(dictionary=True)

        # Check for duplicate user email
        cursor.execute("SELECT id FROM users WHERE email = %s", (email,))
        if cursor.fetchone():
            return jsonify({"error": "Email is already registered. Please log in instead."}), 409

        # Insert user account with role='student'
        cursor.execute(
            "INSERT INTO users (full_name, email, password, role) VALUES (%s, %s, %s, %s)",
            (full_name, email, hashed, role)
        )
        user_id = cursor.lastrowid

        # Check if student academic record already exists in students table (e.g. pre-added by admin)
        cursor.execute("SELECT id FROM students WHERE email = %s", (email,))
        existing_student = cursor.fetchone()
        if not existing_student:
            # Auto-create student profile record so student dashboard and predictions work immediately
            auto_student_id = generate_student_code(cursor)
            cursor.execute(
                """INSERT INTO students
                   (student_id, full_name, email, course, semester, attendance, previous_marks)
                   VALUES (%s, %s, %s, 'General', 1, NULL, NULL)""",
                (auto_student_id, full_name, email)
            )

        conn.commit()

        user_payload = {
            "id": user_id,
            "full_name": full_name,
            "email": email,
            "role": role
        }

        # Generate secure JWT authentication token
        token = generate_token(user_payload)

        return jsonify({
            "message": "User registered successfully",
            "token": token,
            "user": user_payload
        }), 201

    except Exception as e:
        if conn:
            conn.rollback()
        return jsonify({"error": str(e)}), 500
    finally:
        if cursor:
            cursor.close()
        if conn:
            conn.close()


@auth_bp.route("/login", methods=["POST"])
def login():
    """Authenticate a user and return a JWT token and user profile."""
    data = request.get_json() or {}

    email    = str(data.get("email", "")).strip().lower()
    password = str(data.get("password", ""))

    if not email or not password:
        return jsonify({"error": "Email and password are required"}), 400

    conn = cursor = None
    try:
        conn   = get_db_connection()
        cursor = conn.cursor(dictionary=True)
        cursor.execute(
            "SELECT id, full_name, email, password, role FROM users WHERE email = %s",
            (email,)
        )
        user = cursor.fetchone()

        if not user:
            return jsonify({"error": "Invalid email or password"}), 401

        stored_hash = user["password"]
        if not verify_password(stored_hash, password):
            return jsonify({"error": "Invalid email or password"}), 401

        user_payload = {
            "id":        user["id"],
            "full_name": user["full_name"],
            "email":     user["email"],
            "role":      user["role"]
        }

        # Generate secure JWT authentication token
        token = generate_token(user_payload)

        return jsonify({
            "message": "Login successful",
            "token": token,
            "user": user_payload
        }), 200

    except Exception as e:
        return jsonify({"error": str(e)}), 500
    finally:
        if cursor:
            cursor.close()
        if conn:
            conn.close()


@auth_bp.route("/me", methods=["GET"])
@token_required
def get_me():
    """Return the profile of the currently authenticated user."""
    return jsonify({
        "user": {
            "id": g.current_user["id"],
            "full_name": g.current_user["full_name"],
            "email": g.current_user["email"],
            "role": g.current_user["role"]
        }
    }), 200
