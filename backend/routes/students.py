"""Admin-only student management endpoints."""

from flask import Blueprint, jsonify, request

from auth_utils import admin_required
from database import get_db_connection
from student_codes import generate_student_code


students_bp = Blueprint("students", __name__)


def _serialize_student(row):
    if not row:
        return row
    for key in ("created_at", "updated_at"):
        if row.get(key):
            row[key] = row[key].isoformat()
    for key in ("attendance", "previous_marks"):
        if row.get(key) is not None:
            row[key] = float(row[key])
    if row.get("semester") is not None:
        row["semester"] = int(row["semester"])
    return row


def _student_values(data, existing=None):
    current = existing or {}
    name = str(data.get("full_name", current.get("full_name", ""))).strip()
    email = str(data.get("email", current.get("email", ""))).strip().lower()
    course = str(data.get("course", current.get("course", ""))).strip()
    if not name or not email or not course:
        raise ValueError("Full name, email and course are required.")
    try:
        semester = int(data.get("semester", current.get("semester", 1)))
    except (TypeError, ValueError):
        raise ValueError("Semester must be a valid number.")
    attendance_raw = data.get("attendance", current.get("attendance"))
    if attendance_raw is None or str(attendance_raw).strip() == "":
        attendance = None
    else:
        try:
            attendance = float(attendance_raw)
        except (TypeError, ValueError):
            raise ValueError("Attendance must be a valid number.")
    previous_raw = data.get("previous_marks", current.get("previous_marks"))
    if previous_raw is None or str(previous_raw).strip() == "":
        previous_marks = None
    else:
        try:
            previous_marks = float(previous_raw)
        except (TypeError, ValueError):
            raise ValueError("Previous semester marks must be a valid number.")
    if not 1 <= semester <= 12:
        raise ValueError("Semester must be between 1 and 12.")
    if attendance is not None and not 0 <= attendance <= 100:
        raise ValueError("Attendance must be between 0 and 100.")
    if previous_marks is not None and not 0 <= previous_marks <= 100:
        raise ValueError("Previous semester marks must be between 0 and 100.")
    return name, email, course, semester, attendance, previous_marks


@students_bp.route("/", methods=["GET"])
@admin_required
def get_students():
    search = request.args.get("search", "").strip()
    conn = cursor = None
    try:
        conn = get_db_connection()
        cursor = conn.cursor(dictionary=True)
        query = """SELECT id, student_id, full_name, email, course, semester,
                          attendance, previous_marks, created_at, updated_at
                   FROM students"""
        if search:
            like = f"%{search}%"
            cursor.execute(
                query + """ WHERE full_name LIKE %s OR email LIKE %s OR student_id LIKE %s
                            ORDER BY created_at DESC""",
                (like, like, like),
            )
        else:
            cursor.execute(query + " ORDER BY created_at DESC")
        rows = [_serialize_student(row) for row in cursor.fetchall()]
        return jsonify({"students": rows, "total": len(rows)}), 200
    except Exception as error:
        return jsonify({"error": str(error)}), 500
    finally:
        if cursor:
            cursor.close()
        if conn:
            conn.close()


@students_bp.route("/<int:student_id>", methods=["GET"])
@admin_required
def get_student(student_id):
    conn = cursor = None
    try:
        conn = get_db_connection()
        cursor = conn.cursor(dictionary=True)
        cursor.execute("SELECT * FROM students WHERE id = %s", (student_id,))
        row = cursor.fetchone()
        if not row:
            return jsonify({"error": "Student not found"}), 404
        return jsonify({"student": _serialize_student(row)}), 200
    except Exception as error:
        return jsonify({"error": str(error)}), 500
    finally:
        if cursor:
            cursor.close()
        if conn:
            conn.close()


@students_bp.route("/", methods=["POST"])
@admin_required
def create_student():
    data = request.get_json(silent=True) or {}
    if "student_id" in data or "student_code" in data or "id" in data:
        return jsonify({"error": "Student codes are generated by the server and cannot be supplied."}), 400
    try:
        name, email, course, semester, attendance, previous_marks = _student_values(data)
    except ValueError as error:
        return jsonify({"error": str(error)}), 400

    conn = cursor = None
    try:
        conn = get_db_connection()
        cursor = conn.cursor(dictionary=True)
        cursor.execute("SELECT id FROM students WHERE email = %s", (email,))
        if cursor.fetchone():
            return jsonify({"error": f"Email '{email}' is already registered."}), 409

        code = generate_student_code(cursor)
        cursor.execute(
            """INSERT INTO students
               (student_id, full_name, email, course, semester, attendance, previous_marks)
               VALUES (%s, %s, %s, %s, %s, %s, %s)""",
            (code, name, email, course, semester, attendance, previous_marks),
        )
        student_pk = cursor.lastrowid
        conn.commit()
        cursor.execute("SELECT * FROM students WHERE id = %s", (student_pk,))
        return jsonify({
            "message": "Student created successfully",
            "student": _serialize_student(cursor.fetchone()),
        }), 201
    except Exception as error:
        if conn:
            conn.rollback()
        return jsonify({"error": str(error)}), 500
    finally:
        if cursor:
            cursor.close()
        if conn:
            conn.close()


@students_bp.route("/<int:student_id>", methods=["PUT"])
@admin_required
def update_student(student_id):
    data = request.get_json(silent=True) or {}
    if "student_id" in data or "student_code" in data or "id" in data:
        return jsonify({"error": "Student codes are immutable and cannot be supplied."}), 400
    conn = cursor = None
    try:
        conn = get_db_connection()
        cursor = conn.cursor(dictionary=True)
        cursor.execute("SELECT * FROM students WHERE id = %s", (student_id,))
        existing = cursor.fetchone()
        if not existing:
            return jsonify({"error": "Student not found"}), 404
        try:
            name, email, course, semester, attendance, previous_marks = _student_values(data, existing)
        except ValueError as error:
            return jsonify({"error": str(error)}), 400

        cursor.execute(
            "SELECT id FROM students WHERE email = %s AND id != %s",
            (email, student_id),
        )
        if cursor.fetchone():
            return jsonify({"error": f"Email '{email}' is already used by another student."}), 409
        cursor.execute(
            """UPDATE students SET full_name = %s, email = %s, course = %s,
                   semester = %s, attendance = %s, previous_marks = %s
               WHERE id = %s""",
            (name, email, course, semester, attendance, previous_marks, student_id),
        )
        conn.commit()
        cursor.execute("SELECT * FROM students WHERE id = %s", (student_id,))
        return jsonify({
            "message": "Student updated successfully",
            "student": _serialize_student(cursor.fetchone()),
        }), 200
    except Exception as error:
        if conn:
            conn.rollback()
        return jsonify({"error": str(error)}), 500
    finally:
        if cursor:
            cursor.close()
        if conn:
            conn.close()


@students_bp.route("/<int:student_id>", methods=["DELETE"])
@admin_required
def delete_student(student_id):
    conn = cursor = None
    try:
        conn = get_db_connection()
        cursor = conn.cursor()
        cursor.execute("DELETE FROM students WHERE id = %s", (student_id,))
        if cursor.rowcount == 0:
            return jsonify({"error": "Student not found"}), 404
        conn.commit()
        return jsonify({"message": "Student deleted successfully"}), 200
    except Exception as error:
        if conn:
            conn.rollback()
        return jsonify({"error": str(error)}), 500
    finally:
        if cursor:
            cursor.close()
        if conn:
            conn.close()
